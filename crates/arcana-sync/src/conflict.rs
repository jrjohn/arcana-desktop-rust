//! Conflict resolution (C# `ConflictResolver.cs`).
//!
//! ## Field-level merge without reflection
//!
//! C# walks the entity's public properties with reflection, looks for a sibling
//! `{Name}ModifiedAt` timestamp property, and declares `[MergeStrategy]`, `[LocalOnly]` and
//! `[RemoteOnly]` attributes (which its `ResolveFieldLevel` never actually reads). Rust has no
//! runtime reflection, so a type opts in by listing its fields explicitly in
//! [`Mergeable::fields`] as [`FieldDescriptor`]s. Each descriptor carries:
//! - how to compare and copy the field (`same` / `take`, normally generated by [`field!`]);
//! - an optional per-field timestamp accessor (the `{Name}ModifiedAt` convention);
//! - a [`FieldPolicy`] — the attribute semantics, which *are* honoured here:
//!   `LocalOnly` always keeps the local value, `RemoteOnly` always takes the remote value,
//!   `Merge(FirstWriterWins)` keeps the older write, any other `Merge(_)` is last-writer-wins.
//!
//! Fields not listed are taken from the local version.

use std::any::{Any, TypeId};
use std::collections::HashMap;
use std::fmt;
use std::sync::Arc;

use arcana_core::{Timestamp, utc_now};

use crate::{CausalRelation, VectorClock};

/// Conflict resolution strategy (C# `ConflictResolutionStrategy`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum ConflictResolutionStrategy {
    /// Later timestamp wins.
    #[default]
    LastWriterWins,
    /// Earlier timestamp wins.
    FirstWriterWins,
    /// Merge field by field.
    FieldLevelMerge,
    /// Keep both for manual resolution. Like C#, the immediate result falls back to
    /// last-writer-wins; both versions stay available on the result.
    KeepBoth,
    /// Use the resolver registered with [`ConflictResolver::configure_custom`].
    Custom,
}

impl fmt::Display for ConflictResolutionStrategy {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Debug::fmt(self, f)
    }
}

/// Per-field merge policy (C# `[MergeStrategy]`, `[LocalOnly]`, `[RemoteOnly]`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FieldPolicy {
    Merge(ConflictResolutionStrategy),
    LocalOnly,
    RemoteOnly,
}

impl Default for FieldPolicy {
    fn default() -> Self {
        Self::Merge(ConflictResolutionStrategy::LastWriterWins)
    }
}

/// Describes one mergeable field of `T`.
pub struct FieldDescriptor<T> {
    pub name: &'static str,
    pub policy: FieldPolicy,
    /// Whether the field is equal in both versions.
    pub same: fn(&T, &T) -> bool,
    /// Copy the field from the second argument into the first.
    pub take: fn(&mut T, &T),
    /// The field's own modification time (C# `{Name}ModifiedAt`).
    pub modified_at: Option<fn(&T) -> Timestamp>,
}

impl<T> FieldDescriptor<T> {
    /// A last-writer-wins field without its own timestamp.
    #[must_use]
    pub fn new(name: &'static str, same: fn(&T, &T) -> bool, take: fn(&mut T, &T)) -> Self {
        Self {
            name,
            policy: FieldPolicy::default(),
            same,
            take,
            modified_at: None,
        }
    }

    #[must_use]
    pub fn policy(mut self, policy: FieldPolicy) -> Self {
        self.policy = policy;
        self
    }

    #[must_use]
    pub fn modified_at(mut self, f: fn(&T) -> Timestamp) -> Self {
        self.modified_at = Some(f);
        self
    }
}

impl<T> fmt::Debug for FieldDescriptor<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("FieldDescriptor")
            .field("name", &self.name)
            .field("policy", &self.policy)
            .field("has_modified_at", &self.modified_at.is_some())
            .finish_non_exhaustive()
    }
}

/// Build a [`FieldDescriptor`] for `field` of `$t` (compared with `==`, copied with `clone`).
#[macro_export]
macro_rules! field {
    ($t:ty, $f:ident) => {
        $crate::FieldDescriptor::<$t>::new(
            stringify!($f),
            |a, b| a.$f == b.$f,
            |dst, src| dst.$f = src.$f.clone(),
        )
    };
}

/// A type the resolver can work on.
pub trait Mergeable: Clone + Send + Sync + 'static {
    /// Identifier used for deterministic tie-breaking (C# `Id` / `EntityId` property).
    fn entity_id(&self) -> String;

    /// Fields for [`ConflictResolutionStrategy::FieldLevelMerge`]; none by default.
    #[must_use]
    fn fields() -> Vec<FieldDescriptor<Self>> {
        Vec::new()
    }
}

/// A detected conflict (C# `SyncConflict<T>`).
#[derive(Debug, Clone, PartialEq)]
pub struct SyncConflict<T> {
    pub entity_id: String,
    pub local_version: T,
    pub remote_version: T,
    pub local_clock: VectorClock,
    pub remote_clock: VectorClock,
    pub relation: CausalRelation,
    pub detected_at: Timestamp,
    is_resolved: bool,
    resolved_version: Option<T>,
}

impl<T> SyncConflict<T> {
    #[must_use]
    pub fn new(
        entity_id: impl Into<String>,
        local: (T, VectorClock),
        remote: (T, VectorClock),
        relation: CausalRelation,
    ) -> Self {
        Self {
            entity_id: entity_id.into(),
            local_version: local.0,
            remote_version: remote.0,
            local_clock: local.1,
            remote_clock: remote.1,
            relation,
            detected_at: utc_now(),
            is_resolved: false,
            resolved_version: None,
        }
    }

    #[must_use]
    pub fn is_resolved(&self) -> bool {
        self.is_resolved
    }

    #[must_use]
    pub fn resolved_version(&self) -> Option<&T> {
        self.resolved_version.as_ref()
    }

    pub fn resolve(&mut self, resolved: T) {
        self.resolved_version = Some(resolved);
        self.is_resolved = true;
    }
}

/// Outcome of [`ConflictResolver::resolve`] (C# `ConflictResolutionResult<T>`).
#[derive(Debug, Clone, PartialEq)]
pub struct ConflictResolutionResult<T> {
    pub result: T,
    pub merged_clock: VectorClock,
    pub had_conflict: bool,
    pub resolution: String,
    /// Both versions, only when there was a conflict.
    pub local_version: Option<T>,
    pub remote_version: Option<T>,
}

type CustomFn<T> = Arc<dyn Fn(&SyncConflict<T>) -> T + Send + Sync>;

/// Resolves concurrent versions per entity type (C# `ConflictResolver`).
pub struct ConflictResolver {
    node_id: String,
    strategies: HashMap<TypeId, ConflictResolutionStrategy>,
    custom: HashMap<TypeId, Box<dyn Any + Send + Sync>>,
}

impl fmt::Debug for ConflictResolver {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ConflictResolver")
            .field("node_id", &self.node_id)
            .field("strategies", &self.strategies.len())
            .field("custom", &self.custom.len())
            .finish()
    }
}

impl ConflictResolver {
    #[must_use]
    pub fn new(node_id: impl Into<String>) -> Self {
        Self {
            node_id: node_id.into(),
            strategies: HashMap::new(),
            custom: HashMap::new(),
        }
    }

    #[must_use]
    pub fn node_id(&self) -> &str {
        &self.node_id
    }

    /// Strategy for `T` (C# `Configure<T>`).
    pub fn configure<T: Mergeable>(&mut self, strategy: ConflictResolutionStrategy) {
        self.strategies.insert(TypeId::of::<T>(), strategy);
    }

    /// Custom resolver for `T` (C# `ConfigureCustom<T>`).
    pub fn configure_custom<T: Mergeable>(
        &mut self,
        resolver: impl Fn(&SyncConflict<T>) -> T + Send + Sync + 'static,
    ) {
        let f: CustomFn<T> = Arc::new(resolver);
        self.strategies
            .insert(TypeId::of::<T>(), ConflictResolutionStrategy::Custom);
        self.custom.insert(TypeId::of::<T>(), Box::new(f));
    }

    /// The strategy that applies to `T` (last-writer-wins unless configured).
    #[must_use]
    pub fn strategy_for<T: Mergeable>(&self) -> ConflictResolutionStrategy {
        self.strategies
            .get(&TypeId::of::<T>())
            .copied()
            .unwrap_or_default()
    }

    /// Resolve `local` against `remote` (C# `Resolve<T>`).
    #[must_use]
    pub fn resolve<T: Mergeable>(
        &self,
        local: T,
        remote: T,
        clocks: (&VectorClock, &VectorClock),
        timestamps: (Timestamp, Timestamp),
    ) -> ConflictResolutionResult<T> {
        let (local_clock, remote_clock) = clocks;
        let (local_ts, remote_ts) = timestamps;
        let relation = local_clock.compare_to(remote_clock);
        let no_conflict = |result: T, clock: &VectorClock, why: &str| ConflictResolutionResult {
            result,
            merged_clock: clock.clone(),
            had_conflict: false,
            resolution: why.to_owned(),
            local_version: None,
            remote_version: None,
        };
        match relation {
            CausalRelation::HappenedAfter => {
                return no_conflict(local, local_clock, "Local version is newer");
            }
            CausalRelation::HappenedBefore => {
                return no_conflict(remote, remote_clock, "Remote version is newer");
            }
            CausalRelation::Equal => {
                return no_conflict(local, local_clock, "Versions are identical");
            }
            CausalRelation::Concurrent => {}
        }

        let strategy = self.strategy_for::<T>();
        let merged_clock = local_clock.merge(remote_clock).increment(&self.node_id);
        let resolved = match strategy {
            ConflictResolutionStrategy::FirstWriterWins => {
                first_writer_wins(&local, &remote, local_ts, remote_ts)
            }
            ConflictResolutionStrategy::FieldLevelMerge => {
                field_level(&local, &remote, local_ts, remote_ts)
            }
            ConflictResolutionStrategy::Custom => {
                match self
                    .custom
                    .get(&TypeId::of::<T>())
                    .and_then(|b| b.downcast_ref::<CustomFn<T>>())
                {
                    Some(f) => f(&SyncConflict::new(
                        local.entity_id(),
                        (local.clone(), local_clock.clone()),
                        (remote.clone(), remote_clock.clone()),
                        relation,
                    )),
                    None => last_writer_wins(&local, &remote, local_ts, remote_ts),
                }
            }
            ConflictResolutionStrategy::LastWriterWins | ConflictResolutionStrategy::KeepBoth => {
                last_writer_wins(&local, &remote, local_ts, remote_ts)
            }
        };
        ConflictResolutionResult {
            result: resolved,
            merged_clock,
            had_conflict: true,
            resolution: format!("Resolved using {strategy}"),
            local_version: Some(local),
            remote_version: Some(remote),
        }
    }
}

fn last_writer_wins<T: Mergeable>(local: &T, remote: &T, lt: Timestamp, rt: Timestamp) -> T {
    if rt > lt {
        remote.clone()
    } else if lt > rt || local.entity_id() > remote.entity_id() {
        local.clone()
    } else {
        remote.clone()
    }
}

fn first_writer_wins<T: Mergeable>(local: &T, remote: &T, lt: Timestamp, rt: Timestamp) -> T {
    if rt < lt {
        remote.clone()
    } else if lt < rt || local.entity_id() < remote.entity_id() {
        local.clone()
    } else {
        remote.clone()
    }
}

fn field_level<T: Mergeable>(local: &T, remote: &T, lt: Timestamp, rt: Timestamp) -> T {
    let mut result = local.clone();
    for f in T::fields() {
        if (f.same)(local, remote) {
            continue;
        }
        let (l, r) = match f.modified_at {
            Some(at) => (at(local), at(remote)),
            None => (lt, rt),
        };
        let take_remote = match f.policy {
            FieldPolicy::LocalOnly => false,
            FieldPolicy::RemoteOnly => true,
            FieldPolicy::Merge(ConflictResolutionStrategy::FirstWriterWins) => r < l,
            FieldPolicy::Merge(_) => r > l,
        };
        if take_remote {
            (f.take)(&mut result, remote);
        }
    }
    result
}
